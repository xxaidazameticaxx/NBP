CREATE TABLE NBP_ATTENDANCE_ALERT (
  ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_ID        NUMBER NOT NULL,
  COURSE_ID         NUMBER NOT NULL,
  RISK_LEVEL        VARCHAR2(20) NOT NULL,
  ATTENDANCE_RATE   NUMBER(5,2) NOT NULL,
  WEEKLY_TREND      NUMBER(5,2) NOT NULL,
  ALERT_REASON      VARCHAR2(1000),
  CREATED_AT        TIMESTAMP NOT NULL,
  IS_RESOLVED       NUMBER(1) DEFAULT 0 NOT NULL,
  ACTION_TAKEN      VARCHAR2(1000),
  RESOLVED_AT       TIMESTAMP,
  WEEKS_ANALYZED    NUMBER(2)
);
